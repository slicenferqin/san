import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import * as path from "node:path";
import { resetSettingsForTest, Settings } from "@san/coding-agent/config/settings";
import { EditTool } from "@san/coding-agent/edit";
import type { ToolSession } from "@san/coding-agent/tools";
import { TempDir } from "@san/utils";

function createToolSession(cwd: string, settings: Settings): ToolSession {
	return {
		cwd,
		hasUI: false,
		getSessionFile: () => null,
		getSessionSpawns: () => "*",
		enableLsp: false,
		settings,
		getArtifactsDir: () => null,
		getSessionId: () => null,
		getPlanModeState: () => undefined,
	} as unknown as ToolSession;
}

describe("Benchmark Settings 隔离", () => {
	let tempDir: TempDir;

	beforeEach(() => {
		resetSettingsForTest();
		tempDir = TempDir.createSync("san-benchmark-settings-");
	});

	afterEach(async () => {
		resetSettingsForTest();
		await tempDir.remove();
	});

	test("串行运行时让 EditTool 使用当前隔离配置，并在结束后恢复全局状态", async () => {
		const filePath = tempDir.join("fixture.txt");
		await Bun.write(filePath, "initial\n");

		const first = Settings.isolated({ "edit.mode": "apply_patch", "edit.blockAutoGenerated": true });
		await Settings.runWithActiveInstance(first, async () => {
			expect(await Settings.init()).toBe(first);
			const tool = new EditTool(createToolSession(tempDir.path(), first));
			const result = await tool.execute("first-edit", {
				input: [
					"*** Begin Patch",
					`*** Update File: ${path.basename(filePath)}`,
					"@@",
					"-initial",
					"+first",
					"*** End Patch",
					"",
				].join("\n"),
			});
			expect(result.isError).toBeUndefined();
		});

		const second = Settings.isolated({ "edit.mode": "apply_patch", "edit.blockAutoGenerated": false });
		await Settings.runWithActiveInstance(second, async () => {
			expect(await Settings.init()).toBe(second);
			const tool = new EditTool(createToolSession(tempDir.path(), second));
			const result = await tool.execute("second-edit", {
				input: [
					"*** Begin Patch",
					`*** Update File: ${path.basename(filePath)}`,
					"@@",
					"-first",
					"+second",
					"*** End Patch",
					"",
				].join("\n"),
			});
			expect(result.isError).toBeUndefined();
		});

		expect(await Bun.file(filePath).text()).toBe("second\n");
		expect(() => Settings.instance).toThrow("Settings not initialized");
	});
});
